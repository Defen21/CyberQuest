const LEVEL = { Pemula: 'Beginner', Menengah: 'Intermediate', Lanjutan: 'Advanced' };
const RULES = [
    [/^(.+) - CyberQuest$/, (_, a) => `${t(a)} - CyberQuest`],
    [/^(Pemula|Menengah|Lanjutan): (.+)$/, (_, l, a) => `${LEVEL[l]}: ${t(a)}`],
    [/^Level (Pemula|Menengah|Lanjutan)$/, (_, l) => `${LEVEL[l]} level`],
    [/^Kuis level (Pemula|Menengah|Lanjutan)$/, (_, l) => `${LEVEL[l]} level quizzes`],
    [/^Topik: (.+)$/, (_, a) => `Topic: ${t(a)}`],
    [/^Contoh: (.+)$/, 'e.g. $1'],
    [/^Ubah (.+)$/, (_, a) => `Edit ${t(a)}`],
    [/^Hapus (.+)$/, (_, a) => `Delete ${t(a)}`],
    [/^Progres (.+)$/, (_, a) => `${a}'s progress`],
    [/^Didapat (\d+) Okt (\d{4})$/, 'Earned $1 Oct $2'],
    [/^(\d+) Okt (\d{4})$/, '$1 Oct $2'],
    [/^Dimiliki (\d+)% peserta$/, 'Owned by $1% of participants'],
    [/^(\d+) jam lalu$/, '$1 hours ago'],
    [/^(\d+) hari lalu$/, '$1 days ago'],
    [/^(\d+) hari$/, '$1 days'],
    [/^(\d+) menit$/, '$1 min'],
    [/^(\d+) peserta$/, '$1 participants'],
    [/^(\d+) badge$/, '$1 badges'],
    [/^(\d+) soal$/, '$1 questions'],
    [/^(\d+) transaksi$/, '$1 transactions'],
    [/^\+(\d+) XP, (\d+) kali$/, '+$1 XP, $2 times'],
    [/^(\d+) dari (\d+) soal benar$/, '$1 of $2 correct'],
    [/^(\d+) dari (\d+)$/, '$1 of $2'],
    [/^dari (\d+)$/, 'of $1'],
    [/^ke-(\d+) dari (\d+)$/, '$1 of $2'],
    [/^Lulus \(KKM (\d+)\)$/, 'Passed (pass mark $1)'],
    [/^Belum lulus \(KKM (\d+)\)$/, 'Not passed (pass mark $1)'],
];

function t(s) {
    if (LANG !== 'en') return s;
    const key = s.replace(/\s+/g, ' ').trim();
    if (!key) return s;
    let out = EN[key];
    if (out === undefined) {
        const rule = RULES.find(([re]) => re.test(key));
        if (!rule) return s;
        out = key.replace(rule[0], rule[1]);
    }
    return s.replace(/\S[\s\S]*\S|\S/, out);
}

if (LANG === 'en') {
    document.documentElement.lang = 'en';
    document.title = t(document.title);
    const desc = document.querySelector('meta[name="description"]');
    if (desc) desc.content = t(desc.content);
    const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT, {
        acceptNode: (n) => (n.parentElement.closest('script, style') ? NodeFilter.FILTER_REJECT : NodeFilter.FILTER_ACCEPT),
    });
    for (let n = walker.nextNode(); n; n = walker.nextNode()) n.nodeValue = t(n.nodeValue);
    document.querySelectorAll('[placeholder], [aria-label], [title], img[alt]').forEach((el) => {
        ['placeholder', 'aria-label', 'title', 'alt'].forEach((a) => { if (el.hasAttribute(a)) el.setAttribute(a, t(el.getAttribute(a))); });
    });
}

document.querySelectorAll('[data-lang-toggle]').forEach((btn) => {
    btn.textContent = LANG === 'en' ? 'ID' : 'EN';
    btn.setAttribute('aria-label', LANG === 'en' ? 'Ganti bahasa ke Indonesia' : 'Switch language to English');
    btn.addEventListener('click', () => {
        try { localStorage.setItem('lang', LANG === 'en' ? 'id' : 'en'); } catch (e) {}
        window.location.reload();
    });
});
